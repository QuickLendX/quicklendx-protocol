/// Kept comfortably above `payments::transfer::MIN_TRANSFER` so the fixture is
/// valid both under `cfg(test)` (10) and outside it (1 000 000).
const INVOICE_AMOUNT: i128 = 1_000_000_000;
const BID_AMOUNT: i128 = 900_000_000;
const EXPECTED_RETURN: i128 = 1_000_000_000;
const FUNDING: i128 = 2_000_000_000;
const START_TIMESTAMP: u64 = 1_700_000_000;
const DUE_OFFSET: u64 = 30 * 86_400;

// ─────────────────────────────────────────────────────────────────────────────
// Reference model
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum MStatus {
    None,
    Pending,
    Verified,
    Funded,
    Paid,
    Defaulted,
    Cancelled,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum MBid {
    None,
    Placed,
    Accepted,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum MEscrow {
    None,
    Held,
    Released,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum MInvestment {
    None,
    Active,
    Completed,
    Defaulted,
}

/// Operations generated by the proptest strategy.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Op {
    Upload,
    Verify,
    Bid,
    Accept,
    Settle,
    Cancel,
    Default,
}

fn arb_op() -> impl Strategy<Value = Op> {
    prop_oneof![
        Just(Op::Upload),
        Just(Op::Verify),
        Just(Op::Bid),
        Just(Op::Accept),
        Just(Op::Settle),
        Just(Op::Cancel),
        Just(Op::Default),
    ]
}

/// Hand-written oracle for the documented cross-machine lifecycle.
#[derive(Clone, Debug)]
struct Model {
    status: MStatus,
    /// Bid statuses in placement order. The lifecycle allows more than one
    /// open bid, so each bid is tracked independently.
    bids: std::vec::Vec<MBid>,
    escrow: MEscrow,
    investment: MInvestment,
}

impl Model {
    fn new() -> Self {
        Self {
            status: MStatus::None,
            bids: std::vec::Vec::new(),
            escrow: MEscrow::None,
            investment: MInvestment::None,
        }
    }

    /// Advance the model and return whether the contract is expected to accept
    /// the operation.
    fn predict(&mut self, op: Op) -> bool {
        match op {
            Op::Upload => {
                if self.status != MStatus::None {
                    return false;
                }
                self.status = MStatus::Pending;
                true
            }
            Op::Verify => {
                if self.status != MStatus::Pending {
                    return false;
                }
                self.status = MStatus::Verified;
                true
            }
            Op::Bid => {
                if self.status != MStatus::Verified {
                    return false;
                }
                self.bids.push(MBid::Placed);
                true
            }
            Op::Accept => {
                if self.status != MStatus::Verified || self.escrow != MEscrow::None {
                    return false;
                }
                // The fixture accepts the most recently placed open bid.
                let Some(index) = self.bids.iter().rposition(|bid| *bid == MBid::Placed) else {
                    return false;
                };
                self.bids[index] = MBid::Accepted;
                self.status = MStatus::Funded;
                self.escrow = MEscrow::Held;
                self.investment = MInvestment::Active;
                true
            }
            Op::Settle => {
                if self.status != MStatus::Funded {
                    return false;
                }
                self.status = MStatus::Paid;
                self.escrow = MEscrow::Released;
                self.investment = MInvestment::Completed;
                true
            }
            Op::Cancel => {
                if self.status != MStatus::Pending && self.status != MStatus::Verified {
                    return false;
                }
                self.status = MStatus::Cancelled;
                true
            }
            Op::Default => {
                if self.status != MStatus::Funded {
                    return false;
                }
                self.status = MStatus::Defaulted;
                self.investment = MInvestment::Defaulted;
                true
            }
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Fixture + operation execution
// ─────────────────────────────────────────────────────────────────────────────

struct Fixture {
    env: Env,
    client: crate::QuickLendXContractClient<'static>,
    contract_id: Address,
    business: Address,
    investor: Address,
    currency: Address,
    invoice_id: Option<BytesN<32>>,
    /// Bid ids in placement order (only successfully placed bids).
    bid_ids: std::vec::Vec<BytesN<32>>,
    due_date: u64,
}

impl Fixture {
    fn new() -> Self {
        let env = Env::default();
        env.mock_all_auths();
        env.ledger().set_timestamp(START_TIMESTAMP);

        let contract_id = env.register(QuickLendXContract, ());
        let client = crate::QuickLendXContractClient::new(&env, &contract_id);

        let admin = Address::generate(&env);
        client.set_admin(&admin);
        client.initialize_fee_system(&admin);
        client.initialize_protocol_limits(&admin);

        let business = Address::generate(&env);
        client.submit_kyc_application(&business, &String::from_str(&env, "model-business"));
        client.verify_business(&admin, &business);

        let investor = Address::generate(&env);
        client.submit_investor_kyc(&investor, &String::from_str(&env, "model-investor"));
        client.verify_investor(&investor, &10_000_000_000);

        // Real SAC so accept/settle move real value into and out of escrow.
        let token_admin = Address::generate(&env);
        let currency = env
            .register_stellar_asset_contract_v2(token_admin)
            .address();
        let sac = token::StellarAssetClient::new(&env, &currency);
        sac.mint(&business, &FUNDING);
        sac.mint(&investor, &FUNDING);
        let tok = token::Client::new(&env, &currency);
        let expiry = env.ledger().sequence() + 100_000;
        tok.approve(&business, &contract_id, &FUNDING, &expiry);
        tok.approve(&investor, &contract_id, &FUNDING, &expiry);

        Self {
            env,
            client,
            contract_id,
            business,
            investor,
            currency,
            invoice_id: None,
            bid_ids: std::vec::Vec::new(),
            due_date: START_TIMESTAMP + DUE_OFFSET,
        }
    }

    /// Run `op` and report whether the contract accepted it.
    fn execute(&mut self, op: Op) -> bool {
        match op {
            Op::Upload => {
                let tags = Vec::new(&self.env);
                let result = self.client.try_store_invoice(
                    &self.business,
                    &INVOICE_AMOUNT,
                    &self.currency,
                    &self.due_date,
                    &String::from_str(&self.env, "lifecycle model invoice"),
                    &InvoiceCategory::Services,
                    &tags,
                    &None,
                );
                match result {
                    Ok(Ok(id)) => {
                        self.invoice_id = Some(id);
                        true
                    }
                    _ => false,
                }
            }
            Op::Verify => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                matches!(self.client.try_verify_invoice(&id), Ok(Ok(_)))
            }
            Op::Bid => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                let salt = BytesN::from_array(&self.env, &[0u8; 32]);
                match self.client.try_place_bid(
                    &self.investor,
                    &id,
                    &BID_AMOUNT,
                    &EXPECTED_RETURN,
                    &salt,
                ) {
                    Ok(Ok(bid_id)) => {
                        self.bid_ids.push(bid_id);
                        true
                    }
                    _ => false,
                }
            }
            Op::Accept => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                let Some(bid_id) = self.bid_ids.last().cloned() else {
                    return false;
                };
                matches!(self.client.try_accept_bid(&id, &bid_id), Ok(Ok(_)))
            }
            Op::Settle => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                let Some(snapshot) = self.client.get_investment(&id) else {
                    return false;
                };
                matches!(
                    self.client
                        .try_settle_invoice(&id, &INVOICE_AMOUNT, &snapshot),
                    Ok(Ok(_))
                )
            }
            Op::Cancel => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                matches!(self.client.try_cancel_invoice(&id), Ok(Ok(_)))
            }
            Op::Default => {
                let Some(id) = self.invoice_id.clone() else {
                    return false;
                };
                // The revision exposes no public default entrypoint; drive the
                // same helper the overdue scan calls, in the contract context.
                let env = self.env.clone();
                let contract_id = self.contract_id.clone();
                env.as_contract(&contract_id, || defaults::handle_default(&env, &id).is_ok())
            }
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Observable-state comparison
// ─────────────────────────────────────────────────────────────────────────────

fn expected_invoice_status(status: MStatus) -> InvoiceStatus {
    match status {
        MStatus::None => panic!("model has no invoice"),
        MStatus::Pending => InvoiceStatus::Pending,
        MStatus::Verified => InvoiceStatus::Verified,
        MStatus::Funded => InvoiceStatus::Funded,
        MStatus::Paid => InvoiceStatus::Paid,
        MStatus::Defaulted => InvoiceStatus::Defaulted,
        MStatus::Cancelled => InvoiceStatus::Cancelled,
    }
}

fn expected_bid_status(bid: MBid) -> Option<BidStatus> {
    match bid {
        MBid::None => None,
        MBid::Placed => Some(BidStatus::Placed),
        MBid::Accepted => Some(BidStatus::Accepted),
    }
}

fn expected_escrow_status(escrow: MEscrow) -> Option<EscrowStatus> {
    match escrow {
        MEscrow::None => None,
        MEscrow::Held => Some(EscrowStatus::Held),
        MEscrow::Released => Some(EscrowStatus::Released),
    }
}

fn expected_investment_status(investment: MInvestment) -> Option<InvestmentStatus> {
    match investment {
        MInvestment::None => None,
        MInvestment::Active => Some(InvestmentStatus::Active),
        MInvestment::Completed => Some(InvestmentStatus::Completed),
        MInvestment::Defaulted => Some(InvestmentStatus::Defaulted),
    }
}

fn assert_observable(fixture: &Fixture, model: &Model, context: &str) {
    let Some(invoice_id) = fixture.invoice_id.clone() else {
        assert_eq!(
            model.status,
            MStatus::None,
            "invoice should not exist: {context}"
        );
        return;
    };

    let invoice = fixture.client.get_invoice(&invoice_id);
    assert_eq!(
        invoice.status,
        expected_invoice_status(model.status),
        "invoice status mismatch after {context}"
    );

    assert_eq!(
        fixture.bid_ids.len(),
        model.bids.len(),
        "bid count mismatch after {context}"
    );
    for (index, (bid_id, expected)) in fixture.bid_ids.iter().zip(model.bids.iter()).enumerate() {
        let bid = fixture
            .client
            .get_bid(bid_id)
            .unwrap_or_else(|| panic!("bid {index} record missing after {context}"));
        assert_eq!(
            bid.status,
            expected_bid_status(*expected).expect("model bid status"),
            "bid {index} status mismatch after {context}"
        );
    }

    match expected_escrow_status(model.escrow) {
        Some(expected) => {
            let escrow = fixture.client.get_escrow_details(&invoice_id);
            assert!(
                escrow.status == expected,
                "escrow status mismatch after {context}"
            );
            if invoice.funded_amount > 0 {
                assert_eq!(
                    escrow.amount, invoice.funded_amount,
                    "escrow amount must equal funded amount after {context}"
                );
            }
        }
        None => assert!(
            fixture.client.try_get_escrow_details(&invoice_id).is_err(),
            "unexpected escrow after {context}"
        ),
    }

    match expected_investment_status(model.investment) {
        Some(expected) => {
            let investment = fixture
                .client
                .get_investment(&invoice_id)
                .unwrap_or_else(|| panic!("investment missing after {context}"));
            assert_eq!(
                investment.status, expected,
                "investment status mismatch after {context}"
            );
            assert_eq!(
                investment.amount, invoice.funded_amount,
                "investment amount must equal funded amount after {context}"
            );
        }
        None => assert!(
            fixture.client.get_investment(&invoice_id).is_none(),
            "unexpected investment after {context}"
        ),
    }

    if invoice.status == InvoiceStatus::Funded
        || invoice.status == InvoiceStatus::Paid
        || invoice.status == InvoiceStatus::Defaulted
    {
        assert!(
            invoice.funded_amount > 0 && invoice.funded_amount <= invoice.amount,
            "funded_amount out of bounds after {context}"
        );
    }
    if invoice.status == InvoiceStatus::Paid {
        assert_eq!(
            invoice.total_paid, invoice.amount,
            "settled invoice must be fully paid after {context}"
        );
    }
}

fn assert_invariants(fixture: &Fixture, context: &str) {
    let env = fixture.env.clone();
    let contract_id = fixture.contract_id.clone();
    let report = env.as_contract(&contract_id, || run_invariant_checks(&env));
    // `check_name` is a Soroban String; report the failing row indices, which
    // map 1:1 to the order in `run_invariant_checks`.
    let failed: std::vec::Vec<u32> = report
        .checks
        .iter()
        .enumerate()
        .filter(|(_, c)| !c.passed)
        .map(|(index, _)| index as u32)
        .collect();
    assert!(
        report.all_passed,
        "invariant failure after {context}: failing check rows {failed:?}"
    );
}

