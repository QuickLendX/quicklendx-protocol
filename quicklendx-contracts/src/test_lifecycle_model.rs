fn config() -> ProptestConfig {
    let cases = std::env::var("PROPTEST_CASES")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(256);
    ProptestConfig {
        cases,
        max_shrink_iters: 512,
        ..ProptestConfig::default()
    }
}

proptest! {
    #![proptest_config(config())]

    /// Drive a random op sequence through the contract and the reference model,
    /// comparing observable state and cross-machine invariants after every step.
    #[test]
    fn lifecycle_model_matches_contract(ops in prop::collection::vec(arb_op(), 1..=24)) {
        let mut fixture = Fixture::new();
        let mut model = Model::new();

        for (index, op) in ops.iter().copied().enumerate() {
            let predicted = model.predict(op);
            let context = std::format!("op {index} ({op:?})");

            // `upload`/`verify` have no rejection path in this revision; only
            // issue them when the model says they are applicable.
            let applicable = match op {
                Op::Upload => predicted,
                Op::Verify => predicted,
                _ => true,
            };

            if applicable {
                let actual = fixture.execute(op);
                prop_assert_eq!(
                    actual,
                    predicted,
                    "contract/model disagreed on acceptance for {}",
                    context
                );
            }

            assert_observable(&fixture, &model, &context);
            assert_invariants(&fixture, &context);
        }
    }
}
