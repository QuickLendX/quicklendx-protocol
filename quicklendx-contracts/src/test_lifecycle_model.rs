//! Stateful proptest model of the invoice / bid / escrow lifecycle (issue #3050).
//!
//! # Why
//! The existing state-matrix suites (`test_invoice_state_matrix`,
//! `test_escrow_state_machine`, `test_bid_state_matrix`) drive one machine at a
//! time with hand-written cases. `docs/FORMAL_MODEL_NOTES.md` describes
//! cross-machine invariants (invoice status ↔ bid status ↔ escrow ↔ investment)
//! that no randomized test checked over long operation sequences.
//!
//! # Model
//! [`Model`] is a tiny reference oracle for the documented state machines. It
//! carries only observable state: invoice status, bid status, escrow status and
//! investment status. After every operation the test asserts that
//!
//! 1. the contract accepted/rejected the operation exactly when the model
//!    predicted (including deliberately rejected operations),
//! 2. the four observable machine states match the model, and
//! 3. `invariants::run_invariant_checks` reports `all_passed`.
//!
//! Funded totals are cross-checked directly: `invoice.funded_amount`,
//! `escrow.amount` and `investment.amount` must agree while a position is live.
//!
//! # Operations
//! `upload`, `verify`, `bid`, `accept`, `settle`, `cancel`, `default`.
//!
//! Two operations have no rejection path in the current contract revision, so
//! they are only issued when the model says they are applicable:
//!
//! - `upload` always mints a fresh invoice id; replaying it would create a
//!   second invoice outside the model's single-invoice view.
//! - `verify` is unconditional in `Invoice::verify` (it does not check the
//!   current status), so issuing it on a funded invoice would be a contract
//!   bug surfaced by a different suite rather than a model mismatch.
//!
//! Every other operation is issued unconditionally and compared, which is what
//! exercises rejected transitions (`accept` before funding, `settle` twice,
//! `cancel` after funding, `default` on a non-funded invoice, ...).
//!
//! # Running
//! Default: 256 cases.
//!
//! ```bash
//! cargo test --lib test_lifecycle_model
//! PROPTEST_CASES=1000 cargo test --features fuzz-tests --lib test_lifecycle_model
//! ```
//!
//! Failing cases are persisted by proptest under `proptest-regressions/` and
//! replayed automatically on the next run.

